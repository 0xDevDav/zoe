def normalize(code: str | None, default: str = DEFAULT) -> str:
    """Map a Telegram language code (``it``, ``en-US``) to a supported language."""
    if not code:
        return default
    base = code.split("-", 1)[0].lower()
    return base if base in SUPPORTED else default


def t(lang: str, key: str, **kwargs: object) -> str:
    """Return the localized string for ``key``, falling back to the default language."""
    catalog = _CATALOG.get(lang, _CATALOG[DEFAULT])
    template = catalog.get(key) or _CATALOG[DEFAULT].get(key, key)
    return template.format(**kwargs) if kwargs else template


def language_name(lang: str) -> str:
    return LANGUAGE_NAME.get(lang, LANGUAGE_NAME[DEFAULT])
